WITH daily_revenue AS (
    SELECT o.order_date,
           ROUND(
               SUM(oi.quantity * p.price * (1 - oi.discount_percent / 100)),
               2
           ) AS daily_revenue
    FROM orders o
    JOIN order_items oi
        ON o.order_id = oi.order_id
    JOIN products p
        ON oi.product_id = p.product_id
    GROUP BY o.order_date
)
SELECT order_date,
       daily_revenue,
       ROUND(
           SUM(daily_revenue) OVER (
               ORDER BY order_date
               ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
           ),
           2
       ) AS running_total_revenue
FROM daily_revenue
ORDER BY order_date;


